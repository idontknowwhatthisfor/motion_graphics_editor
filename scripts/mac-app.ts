/**
 * Put "Motion Graphics.app" in ~/Applications so the editor opens from the
 * Dock, Spotlight and Finder (ED-26). It is a renamed copy of the Electron
 * runtime that loads the app from THIS folder, so `git pull` + `npm run build`
 * + `npm run build:electron` update it; re-run this only after `npm install`
 * changes the Electron version.
 *
 *   npm run app:install
 *
 * Uses only macOS tools: ditto, plutil, sips, iconutil, codesign.
 */
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { ROOT } from "./lib/node-export";

const NAME = "Motion Graphics";
const BUNDLE_ID = "local.motion-graphics-editor";

if (process.platform !== "darwin") {
  console.error("app:install builds a macOS .app; run it on the Mac.");
  process.exit(1);
}
const run = (cmd: string, args: string[]) => {
  const r = spawnSync(cmd, args, { stdio: ["ignore", "inherit", "inherit"] });
  if (r.status !== 0) throw new Error(`${cmd} ${args.join(" ")} failed (${r.status})`);
};

const src = join(ROOT, "node_modules/electron/dist/Electron.app");
if (!existsSync(src)) throw new Error("Electron is not installed; run npm install first.");
for (const f of ["dist/index.html", "dist-electron/main.mjs", "dist-electron/preload.cjs"])
  if (!existsSync(join(ROOT, f))) throw new Error(`Missing ${f}; run npm run build && npm run build:electron`);

const appsDir = join(homedir(), "Applications");
mkdirSync(appsDir, { recursive: true });
const dest = join(appsDir, `${NAME}.app`);
rmSync(dest, { recursive: true, force: true }); // only ever our own generated bundle
run("ditto", [src, dest]);

const contents = join(dest, "Contents");
const plist = join(contents, "Info.plist");
const set = (key: string, type: "string" | "json", value: string) => run("plutil", ["-replace", key, type === "json" ? "-json" : "-string", value, plist]);

// Name, id and executable.
renameSync(join(contents, "MacOS/Electron"), join(contents, `MacOS/${NAME}`));
set("CFBundleExecutable", "string", NAME);
set("CFBundleName", "string", NAME);
set("CFBundleDisplayName", "string", NAME);
set("CFBundleIdentifier", "string", BUNDLE_ID);
set("CFBundleIconFile", "string", "app.icns");
// Files Finder may hand to the app (Open With, drop on the Dock icon).
set(
  "CFBundleDocumentTypes",
  "json",
  JSON.stringify([
    { CFBundleTypeName: "Motion Graphics Project", CFBundleTypeRole: "Editor", LSHandlerRank: "Alternate", LSItemContentTypes: ["public.json"] },
    { CFBundleTypeName: "Image", CFBundleTypeRole: "Viewer", LSHandlerRank: "Alternate", LSItemContentTypes: ["public.png", "public.jpeg", "public.svg-image"] },
    { CFBundleTypeName: "Audio", CFBundleTypeRole: "Viewer", LSHandlerRank: "Alternate", LSItemContentTypes: ["com.microsoft.waveform-audio", "public.mp3", "public.mpeg-4-audio", "public.aiff-audio"] },
    { CFBundleTypeName: "Movie", CFBundleTypeRole: "Viewer", LSHandlerRank: "Alternate", LSItemContentTypes: ["public.mpeg-4", "com.apple.quicktime-movie", "org.webmproject.webm"] },
  ]),
);

// Icon: electron/icon.png -> .iconset -> .icns
const iconset = join(ROOT, ".cache/app.iconset");
rmSync(iconset, { recursive: true, force: true });
mkdirSync(iconset, { recursive: true });
for (const s of [16, 32, 128, 256, 512]) {
  run("sips", ["-z", String(s), String(s), join(ROOT, "electron/icon.png"), "--out", join(iconset, `icon_${s}x${s}.png`)]);
  run("sips", ["-z", String(s * 2), String(s * 2), join(ROOT, "electron/icon.png"), "--out", join(iconset, `icon_${s}x${s}@2x.png`)]);
}
run("iconutil", ["-c", "icns", iconset, "-o", join(contents, "Resources/app.icns")]);
rmSync(join(contents, "Resources/electron.icns"), { force: true });

// The app code: a stub that points at this folder.
rmSync(join(contents, "Resources/default_app.asar"), { force: true });
const appDir = join(contents, "Resources/app");
mkdirSync(appDir, { recursive: true });
writeFileSync(join(appDir, "package.json"), JSON.stringify({ name: "motion-graphics", productName: NAME, version: "0.1.0", type: "module", main: "main.mjs" }, null, 2));
writeFileSync(
  join(appDir, "main.mjs"),
  `// Generated by npm run app:install. Loads the editor from its folder.\nprocess.env.MGE_ROOT = ${JSON.stringify(ROOT)};\nawait import(${JSON.stringify(pathToFileURL(join(ROOT, "electron/start.mjs")).href)});\n`,
);

// Changing the bundle breaks Electron's signature; re-sign ad hoc so macOS runs it.
run("codesign", ["--force", "--deep", "--sign", "-", dest]);
spawnSync("/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister", ["-f", dest]);

console.log(`\nInstalled ${dest}\nOpen it from Spotlight or ~/Applications, then right-click its Dock icon › Options › Keep in Dock.`);
spawnSync("open", ["-R", dest]);
